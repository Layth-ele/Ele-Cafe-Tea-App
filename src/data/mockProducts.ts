import type { Product } from '@/types';

// ── Default price: every tea is sold as $18 / 90g ─────────────────────────────
const PRICE: Record<string, number> = { black: 18, green: 18, white: 18, oolong: 18, rooibos: 18, herbal: 18, flower: 18, fruit: 18 };

// ── Default caffeine per category ─────────────────────────────────────────────
const CAFFEINE: Record<string, Product['caffeine']> = {
  black: 'High', green: 'Medium', white: 'Low', oolong: 'Medium',
  rooibos: 'None', herbal: 'None', flower: 'None', fruit: 'None',
};

// ── Default antioxidant level per category ────────────────────────────────────
// Based on standard tea-processing science:
//   White (least processed) → highest catechins → Ultra High
//   Green (minimal processing) → very high
//   Rooibos → distinct profile (aspalathin) → High
//   Oolong → partial oxidation → High
//   Black → full oxidation reduces catechins → Medium
//   Flower/Fruit blends → variable, generally Medium
//   Herbal → species-dependent, conservative Low default
const ANTIOXIDANTS: Record<string, Product['antioxidants']> = {
  white: 'Ultra High', green: 'Very High',
  rooibos: 'High', oolong: 'High',
  black: 'Medium', flower: 'Medium', fruit: 'Medium',
  herbal: 'Low',
};

// ── Default brewing parameters per category ───────────────────────────────────
const BREWING_TEMP: Record<string, string> = {
  black: '95–100°C', green: '75–80°C', white: '75–80°C', oolong: '90–95°C',
  rooibos: '100°C', herbal: '100°C', flower: '95°C', fruit: '100°C',
};
const BREWING_TIME: Record<string, string> = {
  black: '3–5 min', green: '2–3 min', white: '4–5 min', oolong: '3–5 min',
  rooibos: '5–7 min', herbal: '5–10 min', flower: '4–5 min', fruit: '5–7 min',
};

// Standard retail bag — admin can override per product later.
const DEFAULT_WEIGHT = '90g';

type TeaDef = {
  name: string; slug: string; category: NonNullable<Product['category']>;
  caffeine?: Product['caffeine']; isOrganic?: boolean;
  allergens?: string[]; featured?: boolean; price?: number;
  benefits?: string; ingredients?: string;
  description?: string; origin?: string; regions?: string;
  antioxidants?: Product['antioxidants'];
  brewingTemp?: string; brewingTime?: string; weight?: string;
  servingSuggestions?: Product['servingSuggestions'];
};

function tea(d: TeaDef): Product {
  return {
    id:           d.slug,
    slug:         d.slug,
    name:         d.name,
    category:     d.category,
    price:        d.price ?? PRICE[d.category] ?? 18,
    // Image left blank by design — every product starts without a
    // photo. Admins upload via /admin/products. The TeaPlaceholder
    // SVG renders wherever the image is missing.
    image:        '',
    // Turn 6: stock dropped. Mocks get availability=true so admin
    // demos / Storybook scenarios show teas as buyable by default.
    available:         true,
    availabilityLabel: 'in_stock' as const,
    featured:     d.featured ?? false,
    isActive:     true,
    isOrganic:    d.isOrganic ?? false,
    gstApplicable: false,
    allergens:    d.allergens ?? [],
    caffeine:     d.caffeine ?? CAFFEINE[d.category],
    antioxidants: d.antioxidants ?? ANTIOXIDANTS[d.category],
    avgRating:    0,
    ratingCount:  0,
    description:  d.description ?? '',
    benefits:     d.benefits ?? '',
    ingredients:  d.ingredients ?? '',
    origin:       d.origin ?? '',
    regions:      d.regions ?? '',
    brewingTemp:  d.brewingTemp ?? BREWING_TEMP[d.category],
    brewingTime:  d.brewingTime ?? BREWING_TIME[d.category],
    weight:       d.weight ?? DEFAULT_WEIGHT,
    servingSuggestions: d.servingSuggestions ?? [],
  };
}

